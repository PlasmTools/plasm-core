import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';

const html = readFileSync(new URL('./training.html', import.meta.url), 'utf8');
const script = html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(script);
const elements = new Map();
const element = id => {
  if (!elements.has(id)) elements.set(id, { hidden: true, disabled: false, dataset: {}, textContent: '', value: '', options: [], replaceChildren() { this.options = []; }, add(option) { this.options.push(option); } });
  return elements.get(id);
};
const messages = [];
const listeners = [];
const parent = { postMessage: value => messages.push(value) };
const window = { parent, addEventListener: (_name, handler) => listeners.push(handler) };
const context = { window, document: { getElementById: element }, location: { pathname: '/', href: 'https://app.example/' }, crypto: { randomUUID: () => '00000000-0000-4000-8000-000000000001' }, Option: function(text, value) { this.text = text; this.value = value; }, URL };
vm.runInNewContext(script, context);
const receive = data => listeners.forEach(handler => handler({ source: parent, data }));
const result = value => receive({ method: 'ui/notifications/tool-result', params: { structuredContent: value } });
const session = 'l_AAAAAAAAAAAAAAAAAAAAAA';
result({ logical_session_ref: session, revision: 2, training_state: { state: 'ordinary' } });
assert.equal(element('trainingAction').textContent, 'Turn training on');
assert.match(element('session').textContent, /Selected session:/);
element('trainingAction').onclick();
assert.equal(messages.at(-1).params.arguments.action, 'request');
assert.equal(messages.at(-1).params.arguments.expected_revision, 2);
receive({ id: messages.at(-1).id, result: { structuredContent: { logical_session_ref: session, revision: 3, training_state: { state: 'awaiting_authorization' }, approval_url: 'https://app.example/training/requests/id' } } });
assert.equal(element('trainingAction').hidden, true);
assert.equal(element('open').hidden, false);
element('open').onclick();
assert.equal(messages.at(-1).method, 'ui/open-link');
element('refresh').onclick();
assert.equal(messages.at(-1).params.arguments.action, 'status');
receive({ id: messages.at(-1).id, result: { structuredContent: { logical_session_ref: session, revision: 4, training_state: { state: 'active' } } } });
assert.equal(element('trainingAction').textContent, 'Turn training off');
element('listExecutions').onclick();
assert.equal(messages.at(-1).params.arguments.action, 'executions');
receive({ id: messages.at(-1).id, result: { structuredContent: { executions: [{ execution_id: 'we-example', session_revision: 1 }] } } });
element('executionSelect').value = 'we-example';
element('executionSelect').onchange();
assert.equal(messages.at(-1).params.arguments.action, 'execution');
receive({ id: messages.at(-1).id, result: { structuredContent: { execution_id: 'we-example', source: 'class Example(Program): pass' } } });
assert.match(element('executionSource').textContent, /class Example/);
element('reviewIntent').value = 'Find a record';
element('reviewOutcome').value = 'The record was found';
const beforeInvalid = messages.length;
element('executionSelect').value = 'different-execution';
element('submitReview').onclick();
assert.equal(messages.length, beforeInvalid, 'cannot submit an execution that was not inspected');
element('executionSelect').value = 'we-example';
element('submitReview').onclick();
assert.equal(messages.at(-1).params.name, 'plasm_review');
assert.equal(messages.at(-1).params.arguments.subtasks[0].execution_ids[0], 'we-example');
receive({ id: messages.at(-1).id, result: { structuredContent: { review_ref: 'review-example', status: 'queued' } } });
assert.match(element('submissionStatus').textContent, /Review queued/);
element('trainingAction').onclick();
assert.equal(messages.at(-1).params.arguments.action, 'stop');
assert.equal(messages.at(-1).params.arguments.expected_revision, 4);
console.log('MCP training controls: on, consent handoff, refresh, off');
